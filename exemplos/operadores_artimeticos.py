'''
operadores      função
+                soma
-                subtração
*                multiplicação
/                divisão
//               divisão inteira
%                resto
**               pontência
'''
numero1 = 10
numero2 = 3

#soma
soma = numero1+numero2
print(f"soma:{numero1+numero2}")
print(f"soma:{soma}")#soma
#print("Bruno"+" Gomes") junta as strings

#subtração
print(f"soma:{numero1-numero2}")

#multiplicação
print(f"soma:{numero1*numero2}")

#divisão
print(f"soma:{numero1/numero2}")
print("{:2f}".format(numero1/numero2))

#divisão inteira
print(f"soma:{numero1//numero2}")

#resto
print(f"soma:{numero1%numero2}")

#pontência

print(f"soma:{numero1**numero2}")